//! `parda install` / `uninstall` / `status`. Everything parda adds is marked so it can be removed
//! exactly, and whatever a setting pointed at before parda becomes parda's upstream, so an existing
//! setup (another proxy, a company gateway) keeps working behind it.

use crate::proxy::{PORT, Route};
use serde_json::{Value, json};
use std::fs;
use std::io::{Read, Write};
use std::net::TcpStream;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

const MARK_START: &str = "# >>> parda >>>";
const MARK_END: &str = "# <<< parda <<<";
/// On the start marker when parda had to end the user's last line before its block; removed with it.
const ADDED_NEWLINE: &str = " (newline added)";
/// On the start marker when the file didn't exist before parda; uninstall deletes it if nothing else is in it.
const CREATED: &str = " (file created)";
#[cfg(target_os = "macos")]
const SERVICE: &str = "dev.parda";
pub const ANTHROPIC_DEFAULT: &str = "https://api.anthropic.com";
pub const OPENAI_DEFAULT: &str = "https://api.openai.com/v1";
/// Gemini API (API key), set by `GOOGLE_GEMINI_BASE_URL`.
pub const GEMINI_DEFAULT: &str = "https://generativelanguage.googleapis.com";
/// Gemini CLI signed in with Google, set by `CODE_ASSIST_ENDPOINT`.
pub const GEMINI_CODE_DEFAULT: &str = "https://cloudcode-pa.googleapis.com";

/// (route, environment variables that point a tool at it, the provider when nothing else was set)
const ROUTES: [(&str, &[&str], &str); 4] = [
    ("anthropic", &["ANTHROPIC_BASE_URL", "ANTHROPIC_API_BASE"], ANTHROPIC_DEFAULT),
    ("openai", &["OPENAI_BASE_URL", "OPENAI_API_BASE"], OPENAI_DEFAULT),
    ("gemini", &["GOOGLE_GEMINI_BASE_URL"], GEMINI_DEFAULT),
    ("gemini-code", &["CODE_ASSIST_ENDPOINT"], GEMINI_CODE_DEFAULT),
];

fn home() -> PathBuf {
    PathBuf::from(std::env::var("HOME").expect("HOME is not set"))
}

/// parda's own folder: `~/.parda` (or `PARDA_HOME`, used by the tests).
pub fn dir() -> PathBuf {
    std::env::var_os("PARDA_HOME").map(PathBuf::from).unwrap_or_else(|| home().join(".parda"))
}

pub fn port() -> u16 {
    std::env::var("PARDA_PORT").ok().and_then(|p| p.parse().ok()).unwrap_or(PORT)
}

fn base() -> String {
    format!("http://127.0.0.1:{}", port())
}

fn is_ours(url: &str) -> bool {
    url.contains(&format!("127.0.0.1:{}", port())) || url.contains(&format!("localhost:{}", port()))
}

/// The routes parda serves (`/anthropic`, `/openai`, `/gemini`, `/gemini-code`), each to what the
/// tools used before parda.
pub fn routes(dir: &Path) -> Vec<Route> {
    let saved: Value = fs::read_to_string(dir.join("upstreams.json"))
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or_default();
    ROUTES
        .iter()
        .map(|(name, _, default)| Route {
            prefix: format!("/{name}"),
            upstream: saved[*name].as_str().filter(|u| !u.is_empty() && !is_ours(u)).unwrap_or(default).to_string(),
        })
        .collect()
}

/// The first candidate that is set and isn't parda itself, else what was saved before, else the provider.
fn choose_upstream(candidates: &[Option<String>], saved: Option<&str>, default: &str) -> String {
    candidates
        .iter()
        .flatten()
        .map(|s| s.trim())
        .find(|u| !u.is_empty() && !is_ours(u))
        .or(saved.filter(|u| !is_ours(u)))
        .unwrap_or(default)
        .to_string()
}

fn claude_settings() -> PathBuf {
    std::env::var_os("CLAUDE_CONFIG_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| home().join(".claude"))
        .join("settings.json")
}

/// Every environment variable parda sets, with the parda URL it points at.
fn env_vars() -> Vec<(&'static str, String)> {
    ROUTES.iter().flat_map(|(name, vars, _)| vars.iter().map(move |v| (*v, format!("{}/{name}", base())))).collect()
}

const GENERATED: &str = "# Generated by `parda install`: AI tools send their requests through parda on this machine.\n";

fn env_sh() -> String {
    let bin = dir().join("bin");
    let bin = bin.display();
    let mut s = format!("{GENERATED}case \":$PATH:\" in *\":{bin}:\"*) ;; *) export PATH=\"{bin}:$PATH\" ;; esac\n");
    for (k, v) in env_vars() {
        s += &format!("export {k}=\"{v}\"\n");
    }
    s
}

fn env_fish() -> String {
    let bin = dir().join("bin");
    let bin = bin.display();
    let mut s = format!("{GENERATED}contains -- \"{bin}\" $PATH; or set -gx PATH \"{bin}\" $PATH\n");
    for (k, v) in env_vars() {
        s += &format!("set -gx {k} \"{v}\"\n");
    }
    s
}

/// Startup files that get the marked block. `.zshrc` too, so parda's block runs after anything else
/// that sets the same variables there.
fn rc_files() -> Vec<PathBuf> {
    let h = home();
    let shell = std::env::var("SHELL").unwrap_or_default();
    let mut v = Vec::new();
    if shell.ends_with("zsh") || h.join(".zshenv").exists() || h.join(".zshrc").exists() || cfg!(target_os = "macos") {
        v.push(h.join(".zshenv"));
        if h.join(".zshrc").exists() {
            v.push(h.join(".zshrc"));
        }
    }
    for f in [".bashrc", ".bash_profile"] {
        if h.join(f).exists() || (f == ".bashrc" && shell.ends_with("bash")) {
            v.push(h.join(f));
        }
    }
    v
}

fn fish_file() -> Option<PathBuf> {
    let d = home().join(".config/fish");
    d.exists().then(|| d.join("conf.d/parda.fish"))
}

fn strip_block(s: &str) -> String {
    match (s.find(MARK_START), s.find(MARK_END)) {
        (Some(a), Some(b)) if b > a => {
            let before = if s[a..].starts_with(&format!("{MARK_START}{ADDED_NEWLINE}")) {
                s[..a].strip_suffix('\n').unwrap_or(&s[..a])
            } else {
                &s[..a]
            };
            let after = &s[b + MARK_END.len()..];
            before.to_string() + after.strip_prefix("\r\n").or_else(|| after.strip_prefix('\n')).unwrap_or(after)
        }
        _ => s.to_string(),
    }
}

/// `text` with parda's block at the end. A last line without a newline is ended first (and the marker
/// says so, so uninstall takes that newline away again).
fn with_block(text: &str, block_body: &str, created: bool) -> String {
    let text = strip_block(text);
    if created && text.is_empty() {
        format!("{MARK_START}{CREATED}\n{block_body}{MARK_END}\n")
    } else if text.is_empty() || text.ends_with('\n') {
        format!("{text}{MARK_START}\n{block_body}{MARK_END}\n")
    } else {
        format!("{text}\n{MARK_START}{ADDED_NEWLINE}\n{block_body}{MARK_END}\n")
    }
}

/// A file's text; empty only when it doesn't exist. Any other failure (unreadable, not UTF-8) is an
/// error, so a file parda can't read is never overwritten.
fn read_existing(path: &Path) -> Result<String, String> {
    match fs::read_to_string(path) {
        Ok(t) => Ok(t),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(String::new()),
        Err(e) => Err(format!("couldn't read {} ({e}); left it alone", path.display())),
    }
}

fn write_json(path: &Path, v: &Value) -> Result<(), String> {
    let text = serde_json::to_string_pretty(v).map_err(|e| e.to_string())? + "\n";
    fs::write(path, text).map_err(|e| format!("write {}: {e}", path.display()))
}

/// Points Claude Code's own settings at parda (they win over the shell). Returns the value that was
/// there before, which becomes the upstream. The old value is kept in `previous` for uninstall.
fn claude_on(settings: &Path, previous: &Path, ours: &str) -> Result<Option<String>, String> {
    let text = read_existing(settings)?;
    let mut v: Value = serde_json::from_str(if text.trim().is_empty() { "{}" } else { &text })
        .map_err(|e| format!("{} isn't valid JSON ({e}); left it alone", settings.display()))?;
    if !v.is_object() {
        return Err(format!("{} isn't a JSON object; left it alone", settings.display()));
    }
    let old = v.pointer("/env/ANTHROPIC_BASE_URL").and_then(Value::as_str).map(str::to_string);
    if !previous.exists() && !old.as_deref().is_some_and(is_ours) {
        // The file's own text too, so uninstall can put it back byte for byte if nothing else changed.
        write_json(previous, &json!({ "value": old, "text": text }))?;
    }
    if !v["env"].is_object() {
        v["env"] = json!({});
    }
    v["env"]["ANTHROPIC_BASE_URL"] = json!(ours);
    if let Some(p) = settings.parent() {
        fs::create_dir_all(p).ok();
    }
    write_json(settings, &v)?;
    Ok(old.filter(|o| !is_ours(o)))
}

fn claude_off(settings: &Path, previous: &Path) -> Result<bool, String> {
    let Ok(text) = fs::read_to_string(settings) else { return Ok(false) };
    let mut v: Value = serde_json::from_str(&text).map_err(|e| e.to_string())?;
    if !v.pointer("/env/ANTHROPIC_BASE_URL").and_then(Value::as_str).is_some_and(is_ours) {
        return Ok(false);
    }
    let old: Value =
        fs::read_to_string(previous).ok().and_then(|t| serde_json::from_str(&t).ok()).unwrap_or(json!({"value": null}));
    let env = v["env"].as_object_mut().expect("checked above");
    let saved_text = old["text"].as_str();
    match old["value"].as_str() {
        Some(o) => {
            env.insert("ANTHROPIC_BASE_URL".into(), json!(o));
        }
        None => {
            env.remove("ANTHROPIC_BASE_URL");
            if env.is_empty() {
                v.as_object_mut().expect("object").remove("env");
            }
        }
    }
    // Unchanged since install apart from parda's line: the original text, formatting and all.
    let same = saved_text
        .and_then(|t| serde_json::from_str::<Value>(if t.trim().is_empty() { "{}" } else { t }).ok())
        .is_some_and(|orig| orig == v);
    match saved_text {
        Some(t) if same => fs::write(settings, t).map_err(|e| format!("write {}: {e}", settings.display()))?,
        _ => write_json(settings, &v)?,
    }
    fs::remove_file(previous).ok();
    Ok(true)
}

fn codex_config() -> PathBuf {
    std::env::var_os("CODEX_HOME").map(PathBuf::from).unwrap_or_else(|| home().join(".codex")).join("config.toml")
}

/// The user's own `openai_base_url` line, set aside in place while parda's is in force.
const SET_ASIDE: &str = "# set aside by parda: ";

/// A TOML string value: `"…"` or `'…'` up to its closing quote, or a bare word; comments dropped.
fn toml_value(v: &str) -> String {
    let v = v.trim();
    match v.chars().next() {
        Some(q @ ('"' | '\'')) => v[1..].split(q).next().unwrap_or("").to_string(),
        _ => v.split(['#', ' ', '\t']).next().unwrap_or("").to_string(),
    }
}

/// Codex reads its base URL from `config.toml`, not the shell. Puts a marked `openai_base_url` at the
/// top (top-level keys must come before any `[table]`). A top-level `openai_base_url` of the user's is
/// commented out where it stands and its value returned, to become the upstream. Line endings are kept.
fn codex_on(config: &Path, ours: &str) -> Result<Option<String>, String> {
    let text = strip_block(&read_existing(config)?);
    let nl = if text.contains("\r\n") { "\r\n" } else { "\n" };
    let mut lines: Vec<String> = text.split_inclusive('\n').map(str::to_string).collect();
    let first_table = lines.iter().position(|l| l.trim_start().starts_with('[')).unwrap_or(lines.len());
    let mut old = None;
    if let Some(i) = (0..first_table).find(|&i| {
        lines[i].trim_start().strip_prefix("openai_base_url").is_some_and(|r| r.trim_start().starts_with('='))
    }) {
        old = lines[i].split_once('=').map(|(_, v)| toml_value(v));
        lines[i] = format!("{SET_ASIDE}{}", lines[i]);
    }
    let out = format!("{MARK_START}{nl}openai_base_url = \"{ours}\"{nl}{MARK_END}{nl}") + &lines.concat();
    if let Some(p) = config.parent() {
        fs::create_dir_all(p).ok();
    }
    fs::write(config, out).map_err(|e| format!("write {}: {e}", config.display()))?;
    Ok(old.filter(|o| !o.is_empty() && !is_ours(o)))
}

/// Ok(true) when parda's line was removed, Ok(false) when there was none.
fn codex_off(config: &Path, previous: &Path) -> Result<bool, String> {
    let text = read_existing(config)?;
    if !text.contains(MARK_START) && !text.contains(SET_ASIDE) {
        return Ok(false);
    }
    let mut restored = strip_block(&text).replace(SET_ASIDE, "");
    // parda 0.1 moved the user's line into `previous` instead of setting it aside.
    let old = read_existing(previous)?;
    if !old.is_empty() {
        restored = old + &restored;
    }
    fs::write(config, restored).map_err(|e| format!("couldn't write {}: {e}", config.display()))?;
    fs::remove_file(previous).ok();
    Ok(true)
}

pub fn install() -> Result<(), String> {
    let dir = dir();
    fs::create_dir_all(dir.join("bin")).map_err(|e| format!("create {}: {e}", dir.display()))?;
    let bin = dir.join("bin/parda");
    let me = std::env::current_exe().map_err(|e| e.to_string())?;
    if me != bin {
        let tmp = dir.join("bin/.parda.new");
        fs::copy(&me, &tmp)
            .and_then(|_| fs::rename(&tmp, &bin))
            .map_err(|e| format!("copy the program to {}: {e}", bin.display()))?;
    }
    crate::vault::Vault::load_or_create_key(&dir).map_err(|e| format!("create the key: {e}"))?;
    println!("✓ program and private key in {}", dir.display());

    // Where requests went before parda: shell, then Claude Code's settings, then what we saved last time.
    let saved: Value = fs::read_to_string(dir.join("upstreams.json"))
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or_default();
    let settings = claude_settings();
    let mut claude_old = None;
    if settings.parent().is_some_and(Path::exists) {
        match claude_on(&settings, &dir.join("claude-previous.json"), &format!("{}/anthropic", base())) {
            Ok(old) => {
                claude_old = old;
                println!("✓ Claude Code sends its requests through parda ({})", settings.display());
            }
            Err(e) => println!("• {e}"),
        }
    }
    let codex = codex_config();
    let mut codex_old = None;
    if codex.parent().is_some_and(Path::exists) {
        match codex_on(&codex, &format!("{}/openai", base())) {
            Ok(old) => {
                codex_old = old;
                println!("✓ Codex sends its requests through parda ({})", codex.display());
            }
            Err(e) => println!("• {e}"),
        }
    }
    let mut upstreams = serde_json::Map::new();
    for (name, vars, default) in ROUTES {
        let mut candidates: Vec<Option<String>> = vars.iter().map(|k| std::env::var(k).ok()).collect();
        match name {
            "anthropic" => candidates.push(claude_old.clone()),
            "openai" => candidates.push(codex_old.clone()),
            _ => {}
        }
        let up = choose_upstream(&candidates, saved[name].as_str(), default);
        let label = match name {
            "anthropic" => "Anthropic",
            "openai" => "OpenAI",
            "gemini" => "Gemini (API key)",
            _ => "Gemini CLI (Google sign-in)",
        };
        println!("✓ {label} requests go on to {up}");
        upstreams.insert(name.into(), up.into());
    }
    write_json(&dir.join("upstreams.json"), &Value::Object(upstreams))?;

    fs::write(dir.join("env.sh"), env_sh()).map_err(|e| e.to_string())?;
    let source = format!("[ -f \"{0}\" ] && . \"{0}\"\n", dir.join("env.sh").display());
    let by_hand = format!("{MARK_START}\n{source}{MARK_END}");
    for rc in rc_files() {
        // A file that can't be read or written is reported and skipped; install carries on.
        let created =
            !rc.exists() || fs::read_to_string(&rc).is_ok_and(|t| t.contains(&format!("{MARK_START}{CREATED}")));
        match read_existing(&rc).and_then(|old| {
            fs::write(&rc, with_block(&old, &source, created))
                .map_err(|e| format!("couldn't update {} ({e})", rc.display()))
        }) {
            Ok(()) => println!("✓ new shells use parda ({})", rc.display()),
            Err(e) => println!("• {e}. Add this to it yourself:\n{by_hand}"),
        }
    }
    if let Some(f) = fish_file() {
        fs::create_dir_all(f.parent().expect("has parent")).ok();
        fs::write(&f, env_fish()).map_err(|e| e.to_string())?;
        println!("✓ new fish shells use parda ({})", f.display());
    }

    if std::env::var("PARDA_NO_SERVICE").as_deref() == Ok("1") {
        println!("• skipped the background service (PARDA_NO_SERVICE=1); run `parda run` yourself");
    } else {
        start_service(&bin)?;
    }
    println!("\nOpen a new terminal and restart your AI tools. `parda status` shows what parda is doing.");
    Ok(())
}

pub fn uninstall() {
    let dir = dir();
    if std::env::var("PARDA_NO_SERVICE").as_deref() != Ok("1") {
        stop_service();
    }
    for rc in rc_files() {
        match read_existing(&rc) {
            Ok(old) if old.contains(&format!("{MARK_START}{CREATED}")) && strip_block(&old).is_empty() => {
                if fs::remove_file(&rc).is_ok() {
                    println!("✓ removed {} (parda created it)", rc.display());
                }
            }
            Ok(old) if old.contains(MARK_START) => match fs::write(&rc, strip_block(&old)) {
                Ok(()) => println!("✓ removed from {}", rc.display()),
                Err(e) => println!(
                    "! couldn't update {}: {e}. Remove the lines between the parda markers yourself.",
                    rc.display()
                ),
            },
            Ok(_) => {}
            Err(e) => println!("! {e}. If it has a parda block, remove it yourself."),
        }
    }
    if let Some(f) = fish_file().filter(|f| f.exists()) {
        fs::remove_file(&f).ok();
        println!("✓ removed {}", f.display());
    }
    match claude_off(&claude_settings(), &dir.join("claude-previous.json")) {
        Ok(true) => println!("✓ Claude Code settings put back ({})", claude_settings().display()),
        Ok(false) => {}
        Err(e) => println!("• could not restore {}: {e}", claude_settings().display()),
    }
    match codex_off(&codex_config(), &dir.join("codex-previous.toml")) {
        Ok(true) => println!("✓ Codex settings put back ({})", codex_config().display()),
        Ok(false) => {}
        Err(e) => println!(
            "! {e}. Remove the `openai_base_url` line between the parda markers yourself, or Codex can't connect."
        ),
    }
    for f in ["env.sh", "bin/parda", "upstreams.json"] {
        fs::remove_file(dir.join(f)).ok();
    }
    println!(
        "✓ parda removed. Your key and log stay in {} (delete the folder to remove them too).\n\
         Open a new terminal and restart your AI tools: until then they still point at parda and will show a connection error.",
        dir.display()
    );
}

/// `GET /parda/health` on the local port.
pub fn running() -> bool {
    let Ok(mut s) = TcpStream::connect_timeout(&([127, 0, 0, 1], port()).into(), Duration::from_millis(500)) else {
        return false;
    };
    s.set_read_timeout(Some(Duration::from_secs(1))).ok();
    let req = format!("GET /parda/health HTTP/1.1\r\nhost: 127.0.0.1:{}\r\nconnection: close\r\n\r\n", port());
    if s.write_all(req.as_bytes()).is_err() {
        return false;
    }
    let mut r = String::new();
    s.read_to_string(&mut r).ok();
    r.contains("parda ok")
}

pub fn status() {
    let dir = dir();
    if running() {
        println!("● parda is running on {}", base());
    } else {
        println!("○ parda is NOT running. AI tools pointed at it will show a connection error (nothing is sent).");
        println!("  Start it: `parda install` (background service) or `parda run` (this terminal).");
    }
    for r in routes(&dir) {
        println!("  {}{} → {}", base(), r.prefix, r.upstream);
    }
    for (var, want) in env_vars() {
        match std::env::var(var) {
            Ok(v) if is_ours(&v) => {}
            Ok(v) => println!(
                "! In this shell {var} is {v}, so those requests skip parda. Open a new terminal; if it stays, something sets {var} after parda's block."
            ),
            Err(_) => println!("! {var} isn't set in this shell. Open a new terminal (expected {want})."),
        }
    }
    let day = &crate::log::now_iso()[..10];
    let (requests, kinds) = crate::log::summary(&dir, day);
    let masked: Vec<String> = kinds.iter().filter(|(_, n)| **n > 0).map(|(k, n)| format!("{n} {k}")).collect();
    println!(
        "  today ({day} UTC): {requests} requests, masked {}",
        if masked.is_empty() { "nothing".into() } else { masked.join(", ") }
    );
    println!("  log: {}", dir.join("log.jsonl").display());
}

#[cfg(target_os = "macos")]
fn plist_path() -> PathBuf {
    home().join(format!("Library/LaunchAgents/{SERVICE}.plist"))
}

#[cfg(target_os = "macos")]
fn start_service(bin: &Path) -> Result<(), String> {
    let plist = plist_path();
    fs::create_dir_all(plist.parent().expect("has parent")).ok();
    fs::write(
        &plist,
        format!(
            r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>{SERVICE}</string>
  <key>ProgramArguments</key><array><string>{}</string><string>run</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>ProcessType</key><string>Interactive</string>
  <key>StandardOutPath</key><string>/dev/null</string>
  <key>StandardErrorPath</key><string>{}</string>
</dict></plist>
"#,
            bin.display(),
            dir().join("errors.log").display()
        ),
    )
    .map_err(|e| e.to_string())?;
    let uid = unsafe { libc::getuid() };
    let target = format!("gui/{uid}");
    Command::new("launchctl").args(["bootout", &format!("{target}/{SERVICE}")]).output().ok();
    let ok = (0..40).any(|i| {
        if i > 0 {
            std::thread::sleep(Duration::from_millis(250));
        }
        Command::new("launchctl")
            .args(["bootstrap", &target, &plist.display().to_string()])
            .output()
            .is_ok_and(|o| o.status.success())
    });
    if ok {
        println!("✓ background service running; it starts again at login");
        Ok(())
    } else {
        Err(format!("could not start the background service. Try: launchctl bootstrap {target} {}", plist.display()))
    }
}

#[cfg(target_os = "macos")]
fn stop_service() {
    let uid = unsafe { libc::getuid() };
    Command::new("launchctl").args(["bootout", &format!("gui/{uid}/{SERVICE}")]).output().ok();
    if fs::remove_file(plist_path()).is_ok() {
        println!("✓ background service stopped and removed");
    }
}

#[cfg(target_os = "linux")]
fn unit_path() -> PathBuf {
    home().join(".config/systemd/user/parda.service")
}

#[cfg(target_os = "linux")]
fn start_service(bin: &Path) -> Result<(), String> {
    let unit = unit_path();
    fs::create_dir_all(unit.parent().expect("has parent")).ok();
    fs::write(
        &unit,
        format!(
            "[Unit]\nDescription=parda: masks secrets and personal data before AI tools send them\n\n\
             [Service]\nExecStart=\"{}\" run\nRestart=always\nRestartSec=1\n\n\
             [Install]\nWantedBy=default.target\n",
            bin.display()
        ),
    )
    .map_err(|e| e.to_string())?;
    let systemctl =
        |args: &[&str]| Command::new("systemctl").arg("--user").args(args).output().is_ok_and(|o| o.status.success());
    if systemctl(&["daemon-reload"]) && systemctl(&["enable", "--now", "parda"]) && systemctl(&["restart", "parda"]) {
        println!("✓ background service running (systemd user service); it starts again at login");
    } else {
        println!(
            "• systemd user services aren't available here. Start parda from your shell profile instead:\n    pgrep -u \"$USER\" -f 'parda run' >/dev/null || (nohup \"{}\" run >/dev/null 2>&1 &)",
            bin.display()
        );
    }
    Ok(())
}

#[cfg(target_os = "linux")]
fn stop_service() {
    Command::new("systemctl").args(["--user", "disable", "--now", "parda"]).output().ok();
    if fs::remove_file(unit_path()).is_ok() {
        Command::new("systemctl").args(["--user", "daemon-reload"]).output().ok();
        println!("✓ background service stopped and removed");
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rc_block_is_replaced_not_duplicated_and_removed_exactly() {
        for original in ["export A=1\n", "export A=1", "", "a\r\nb\r\n"] {
            let once = with_block(original, ". x\n", false);
            assert_eq!(with_block(&once, ". x\n", false), once, "{original:?}");
            assert!(once.contains(&format!("\n{MARK_START}")) || original.is_empty(), "block on its own line");
            assert_eq!(strip_block(&once), original, "{original:?}");
        }
    }

    #[test]
    fn upstream_keeps_an_existing_proxy_and_never_points_at_itself() {
        let ours = format!("{}/anthropic", base());
        let headroom = "http://127.0.0.1:8787".to_string();
        assert_eq!(choose_upstream(&[Some(ours.clone()), Some(headroom.clone())], None, ANTHROPIC_DEFAULT), headroom);
        assert_eq!(choose_upstream(&[Some(ours.clone())], Some(&headroom), ANTHROPIC_DEFAULT), headroom);
        assert_eq!(choose_upstream(&[Some(ours.clone()), None], Some(&ours), ANTHROPIC_DEFAULT), ANTHROPIC_DEFAULT);
    }

    #[test]
    fn codex_config_round_trip() {
        let d = std::env::temp_dir().join(format!("parda-codex-{}", std::process::id()));
        fs::create_dir_all(&d).unwrap();
        let (c, p) = (d.join("config.toml"), d.join("previous.toml"));
        let ours = format!("{}/openai", base());
        let original = "model = \"gpt-5\"\r\nopenai_base_url = \"https://gw.example.com/v1\" # corp gateway\r\n\r\n[profiles.x]\r\nopenai_base_url = \"keep\"\r\n";
        fs::write(&c, original).unwrap();
        assert_eq!(codex_on(&c, &ours).unwrap().as_deref(), Some("https://gw.example.com/v1"));
        let on = fs::read_to_string(&c).unwrap();
        assert!(on.starts_with(&format!("{MARK_START}\r\nopenai_base_url = \"{ours}\"\r\n")), "{on:?}");
        assert!(!on.replace("\r\n", "").contains('\n'), "line endings kept: {on:?}");
        assert_eq!(codex_on(&c, &ours).unwrap(), None, "reinstall is a no-op");
        assert!(codex_off(&c, &p).unwrap());
        assert_eq!(fs::read_to_string(&c).unwrap(), original, "back exactly, the user's line where it was");

        // A config from parda 0.1, which kept the user's line in `previous`.
        fs::write(&c, format!("{MARK_START}\nopenai_base_url = \"{ours}\"\n{MARK_END}\nmodel = \"x\"\n")).unwrap();
        fs::write(&p, "openai_base_url = \"https://gw.example.com/v1\"\n").unwrap();
        assert!(codex_off(&c, &p).unwrap());
        assert_eq!(fs::read_to_string(&c).unwrap(), "openai_base_url = \"https://gw.example.com/v1\"\nmodel = \"x\"\n");
        fs::remove_dir_all(&d).ok();
    }

    #[test]
    fn claude_settings_round_trip() {
        let d = std::env::temp_dir().join(format!("parda-test-{}", std::process::id()));
        fs::create_dir_all(&d).unwrap();
        let (s, p) = (d.join("settings.json"), d.join("previous.json"));
        let ours = format!("{}/anthropic", base());

        let original = json!({"model": "x", "env": {"ANTHROPIC_BASE_URL": "http://127.0.0.1:8787", "A": "1"}});
        write_json(&s, &original).unwrap();
        assert_eq!(claude_on(&s, &p, &ours).unwrap().as_deref(), Some("http://127.0.0.1:8787"));
        assert_eq!(claude_on(&s, &p, &ours).unwrap(), None, "reinstall keeps the first saved value");
        assert!(claude_off(&s, &p).unwrap());
        assert_eq!(serde_json::from_str::<Value>(&fs::read_to_string(&s).unwrap()).unwrap(), original);

        let bare = json!({"model": "x"});
        write_json(&s, &bare).unwrap();
        claude_on(&s, &p, &ours).unwrap();
        claude_off(&s, &p).unwrap();
        assert_eq!(serde_json::from_str::<Value>(&fs::read_to_string(&s).unwrap()).unwrap(), bare);

        fs::write(&s, b"{\"a\": \"caf\xe9\"}").unwrap(); // Latin-1 byte: not UTF-8
        assert!(claude_on(&s, &p, &ours).is_err());
        assert_eq!(fs::read(&s).unwrap(), b"{\"a\": \"caf\xe9\"}", "unreadable settings are left alone");
        let toml = d.join("latin1.toml");
        fs::write(&toml, b"model = \"caf\xe9\"\n").unwrap();
        assert!(codex_on(&toml, &ours).is_err());
        assert_eq!(fs::read(&toml).unwrap(), b"model = \"caf\xe9\"\n");

        fs::write(&s, "{ not json").unwrap();
        assert!(claude_on(&s, &p, &ours).is_err());
        assert_eq!(fs::read_to_string(&s).unwrap(), "{ not json", "broken settings are left alone");
        fs::remove_dir_all(&d).ok();
    }
}
